const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const source=fs.readFileSync(path.join(__dirname,'../js/travel-planner.js'),'utf8');
const stay={id:'hotel',name:'2박 숙소',category:'숙소',startTime:'23:00',endTime:'10:00',endDate:'2026-12-13'};
const tour={id:'tour',name:'긴 투어',category:'관광',startTime:'09:00',endTime:'18:00'};
const state={days:[[stay],[tour],[]],expenses:[]};
const ctx=vm.createContext({state,tripDate:d=>'2026-12-'+(11+d),normalizeStop(){},hasStopTime:()=>true,stopStart:s=>s.startTime,stopEnd:s=>s.endTime,scheduleEndDate:(s,d)=>s.endDate||'2026-12-'+(11+d),activeScheduleCard:null,currentTripId:'t',actualTags:()=>'',esc:String,dayColor:()=> '#3182F6',dateLabel:String,TravelComponents:{inlineTools:()=>''}});
vm.runInContext(source.slice(source.indexOf('function scheduleGridEntries('),source.indexOf('let activeScheduleCard = null;')),ctx);
const before=JSON.stringify(state),entries=ctx.scheduleGridEntries(),html=ctx.fullScheduleTable();
assert.equal(entries[0].timed.length,1);
assert.equal(entries[1].timed.length,1,'checkout period leaves the following day free for touring');
assert.equal(entries[2].timed.length,0);
assert.equal(entries[0].timed[0].end-entries[0].timed[0].start,1,'only a compact check-in cell');
assert.equal((html.match(/>2박 숙소</g)||[]).length,1);
assert.match(html,/23:00 → 12\/13 10:00/);
assert.match(html,/grid-lodging-card/);
assert.match(html,/rowspan="18"/,'ordinary long activities still use their real duration');
assert.equal(JSON.stringify(state),before,'display changes never alter the stored booking or checkout time');
console.log('PASS: one compact lodging card, checkout preserved, other days free, and ordinary durations unchanged.');
