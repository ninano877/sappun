const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const source=fs.readFileSync(path.join(__dirname,'../js/travel-planner.js'),'utf8');
const hotel={id:'hotel',name:'1, 2일차 숙소',category:'숙소',query:'Hotel A',startTime:'23:00',endTime:'10:00',endDate:'2026-12-13',placeQuery:'Hotel A',chosenPlace:{lat:34,lng:135}};
const back={id:'return',name:'숙소 복귀',category:'관광',query:'old',startTime:'22:00',endTime:'23:00'};
const data={days:[[hotel],[back]]};
const ctx=vm.createContext({state:data,document:{addEventListener(){}},resolvedPlaces:new Map()});
vm.runInContext(source.slice(source.indexOf('function linkedLodging('),source.indexOf('async function resolvePlace(')),ctx);
vm.runInContext(source.slice(source.indexOf('function savedPoint('),source.indexOf('// Each trip keeps independent map')),ctx);
ctx.applyLodgingLink(back,'hotel');
assert.equal(back.lodgingStopId,'hotel');assert.equal(back.category,'숙소');assert.equal(back.query,'Hotel A');
assert.equal(back.startTime,'22:00');assert.equal(back.endTime,'23:00');assert.equal(back.endDate,undefined);
assert.equal(hotel.endDate,'2026-12-13');assert.equal(ctx.savedPoint(back).lat,34);
hotel.query='Corrected address';ctx.syncLodgingLinks(data);
assert.equal(back.query,'Corrected address');assert.equal(ctx.savedPoint(back),undefined,'old coordinates are not reused after address changes');
hotel.placeQuery=hotel.query;hotel.chosenPlace={lat:35,lng:136};ctx.syncLodgingLinks(data);
assert.equal(ctx.savedPoint(back).lat,35);
assert.throws(()=>ctx.applyLodgingLink(hotel,'return'),/다시 선택/,'linked return schedules cannot become circular booking sources');
ctx.applyLodgingLink(back,'');assert.equal(back.lodgingStopId,undefined);assert.equal(back.query,'Corrected address');
ctx.applyLodgingLink(back,'hotel');data.days[0]=[];ctx.syncLodgingLinks(data);
assert.equal(back.lodgingStopId,undefined,'removing a source safely detaches the return schedule');
assert.equal(back.startTime,'22:00');
console.log('PASS: shared lodging location, independent return times, address updates, unlink, missing source, and cycle prevention.');
